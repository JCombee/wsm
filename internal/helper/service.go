// QuadletUsersDir holds one directory per user with the rootless Quadlet
// units systemd generates user services from. Root owns the files.
const QuadletUsersDir = "/etc/containers/systemd/users"

// ServiceUnitDir returns the Quadlet directory of the service user.
func ServiceUnitDir(svcUID int) string {
	return filepath.Join(QuadletUsersDir, strconv.Itoa(svcUID))
}

// ServiceNames are the names derived from a (service, tag) pair.
type ServiceNames struct {
	Base      string // wsm-mariadb-11-8
	File      string // the Quadlet file: wsm-mariadb-11-8.container
	Unit      string // the generated user service: wsm-mariadb-11-8.service
	Container string // the container name
	Secret    string // the Podman secret with the root password
	Volume    string // the data volume
}

// NamesFor derives the names for a valid service and tag.
func NamesFor(service, tag string) ServiceNames {
	base := "wsm-" + service + "-" + blocks.Slug(tag)
	return ServiceNames{
		Base:      base,
		File:      base + ".container",
		Unit:      base + ".service",
		Container: base,
		Secret:    base + "-root",
		Volume:    base + "-data",
	}
}

// ServiceUnit returns the Quadlet unit of a shared service instance. The
// text is a fixed template; the only variable parts are derived from the
// validated service, tag and port, and the wsm0 address. The password is
// not in it: the container gets it from a Podman secret.
func ServiceUnit(wsm0 netip.Addr, service, tag string, port int) (string, error) {
	b, err := blocks.LookupShared(service)
	if err != nil {
		return "", err
	}
	if err := blocks.ValidTag(tag); err != nil {
		return "", err
	}
	if !netpolicy.ValidServicePort(port) {
		return "", fmt.Errorf("port %d is outside %d-%d", port, netpolicy.ServicePortMin, netpolicy.ServicePortMax)
	}
	if !wsm0.Is4() {
		return "", fmt.Errorf("wsm0 address %v is not IPv4", wsm0)
	}
	n := NamesFor(service, tag)
	var w strings.Builder
	line := func(format string, args ...any) { fmt.Fprintf(&w, format+"\n", args...) }
	line("# Generated by wsm-helper. Do not edit.")
	line("[Unit]")
	line("Description=wsm shared %s %s", service, tag)
	line("")
	line("[Container]")
	line("ContainerName=%s", n.Container)
	line("Image=%s", b.ImageRef(tag))
	line("PublishPort=%s:%d:%d", wsm0, port, b.ContainerPort)
	line("Secret=%s,type=env,target=MARIADB_ROOT_PASSWORD", n.Secret)
	line("Environment=MARIADB_AUTO_UPGRADE=1")
	line("Volume=%s:/var/lib/mysql", n.Volume)
	line("PodmanArgs=--memory=1g --pids-limit=512")
	line("")
	line("[Service]")
	line("Restart=always")
	line("RestartSec=5")
	line("TimeoutStartSec=900")
	line("")
	line("[Install]")
	line("WantedBy=default.target")
	return w.String(), nil
}

// lookupServiceUser returns the account of ServiceUser. Its name and home
// are fixed; the UID comes from passwd and must be neither root nor a
// project UID.
func lookupServiceUser() (account, error) {
	u, err := user.Lookup(ServiceUser)
	if err != nil {
		return account{}, fmt.Errorf("look up %s: %w", ServiceUser, err)
	}
	uid, err := strconv.Atoi(u.Uid)
	if err != nil {
		return account{}, fmt.Errorf("%s has uid %q: %w", ServiceUser, u.Uid, err)
	}
	switch {
	case uid <= 0:
		return account{}, fmt.Errorf("%s has uid %d", ServiceUser, uid)
	case projectuid.Valid(uid):
		return account{}, fmt.Errorf("%s has uid %d, inside the project range", ServiceUser, uid)
	case u.HomeDir != ServiceHome:
		return account{}, fmt.Errorf("%s has home %q, want %q", ServiceUser, u.HomeDir, ServiceHome)
	}
	byID, err := user.LookupId(u.Uid)
	if err != nil || byID.Username != ServiceUser {
		return account{}, fmt.Errorf("uid %d does not belong to %s alone", uid, ServiceUser)
	}
	return account{name: ServiceUser, uid: uid, home: ServiceHome}, nil
}

// serviceAccount returns the service user once its user manager is up.
func serviceAccount(ctx context.Context) (account, error) {
	a, err := lookupServiceUser()
	if err != nil {
		return a, err
	}
	if err := waitFor(ctx, fmt.Sprintf("/run/user/%d/bus", a.uid), 60*time.Second); err != nil {
		return a, fmt.Errorf("user manager of %s: %w", ServiceUser, err)
	}
	return a, nil
}

// svcPodman runs podman for the service user as a transient unit of that
// user's own systemd manager, never as a child of the helper. Podman's
// first call creates a pause process that keeps the caller's mount
// namespace; a child of the helper would leave every later container of
// the user in the helper's PrivateTmp, which is gone once the helper stops
// (ADR 0013). --wait passes podman's exit code back, and --pipe passes
// stdin as a pipe, which "podman secret create -" needs.
func svcPodman(ctx context.Context, a account, stdin *strings.Reader, args ...string) (string, error) {
	podman, err := lookTool("podman")
	if err != nil {
		return "", err
	}
	full := append([]string{"--user", "--wait", "--pipe", "--quiet", "--collect",
		"-p", "RuntimeMaxSec=600", "--", podman}, args...)
	if stdin == nil {
		return runAs(ctx, a, nil, "systemd-run", full...)
	}
	return runAs(ctx, a, stdin, "systemd-run", full...)
}

// checkService validates a service and tag again and returns the block.
func checkService(service, tag string) (blocks.Block, error) {
	b, err := blocks.LookupShared(service)
	if err != nil {
		return b, err
	}
	return b, blocks.ValidTag(tag)
}

// podman runs podman for the service user: svcPodman, or the fake of a
// test.
func (o *SystemOps) podman(ctx context.Context, a account, stdin *strings.Reader, args ...string) (string, error) {
	if o.runPodman != nil {
		return o.runPodman(ctx, a, stdin, args...)
	}
	return svcPodman(ctx, a, stdin, args...)
}

// pullImage pulls the image for tag unless the service user has it. When
// the registry does not know the tag, the error wraps ErrNotFound.
func (o *SystemOps) pullImage(ctx context.Context, a account, b blocks.Block, tag string) error {
	image := b.ImageRef(tag)
	if _, err := o.podman(ctx, a, nil, "image", "exists", image); err == nil {
		return nil
	}
	o.logf("pulling %s", image)
	if out, err := o.podman(ctx, a, nil, "pull", "-q", image); err != nil {
		if strings.Contains(out, "manifest unknown") || strings.Contains(err.Error(), "manifest unknown") {
			return fmt.Errorf("%w: tag %s of %s: %v", ErrNotFound, tag, b.ID, err)
		}
		return err
	}
	return nil
}

// PullServiceImage makes sure the image of a shared block for tag is
// present for the service user.
func (o *SystemOps) PullServiceImage(ctx context.Context, service, tag string) error {
	b, err := checkService(service, tag)
	if err != nil {
		return err
	}
	a, err := serviceAccount(ctx)
	if err != nil {
		return err
	}
	return o.pullImage(ctx, a, b, tag)
}

// EnsureServiceInstance writes and starts the instance of a shared block
// for tag: the image, the root password as a Podman secret, the Quadlet
// unit, and a start of the generated service. Running it again repairs an
// instance and keeps its data.
func (o *SystemOps) EnsureServiceInstance(ctx context.Context, service, tag string, port int, password string) error {
	b, err := checkService(service, tag)
	if err != nil {
		return err
	}
	if !ValidPassword(password) {
		return fmt.Errorf("password must be %d characters from [A-Za-z0-9_-]", PasswordLen)
	}
	unit, err := ServiceUnit(o.WSM0Addr, service, tag, port)
	if err != nil {
		return err
	}
	a, err := serviceAccount(ctx)
	if err != nil {
		return err
	}
	if err := o.pullImage(ctx, a, b, tag); err != nil {
		return err
	}
	n := NamesFor(service, tag)
	if _, err := o.podman(ctx, a, strings.NewReader(password),
		"secret", "create", "--replace", n.Secret, "-"); err != nil {
		return err
	}
	dir := ServiceUnitDir(a.uid)
	if err := ensureRootDirs(filepath.Dir(QuadletUsersDir), QuadletUsersDir, dir); err != nil {
		return err
	}
	if err := writeFileNoFollow(filepath.Join(dir, n.File), []byte(unit), 0o644, 0, 0); err != nil {
		return err
	}
	if _, err := runAs(ctx, a, nil, "systemctl", "--user", "daemon-reload"); err != nil {
		return err
	}
	if _, err := runAs(ctx, a, nil, "systemctl", "--user", "start", "--no-block", n.Unit); err != nil {
		return err
	}
	o.logf("service %s %s ensured on port %d", service, tag, port)
	return nil
}

// ensureRootDirs creates each directory in order, owned by root with mode
// 0755, and checks that each one is a real directory owned by root.
func ensureRootDirs(dirs ...string) error {
	for _, d := range dirs {
		created := false
		if err := os.Mkdir(d, 0o755); err == nil {
			created = true
		} else if !errors.Is(err, os.ErrExist) {
			return fmt.Errorf("mkdir %s: %w", d, err)
		}
		fi, err := os.Lstat(d)
		if err != nil {
			return fmt.Errorf("stat %s: %w", d, err)
		}
		if !fi.IsDir() {
			return fmt.Errorf("%s is not a directory", d)
		}
		if owner, ok := statUID(fi); !ok || owner != 0 {
			return fmt.Errorf("%s is not owned by root", d)
		}
		if created {
			if err := os.Chmod(d, 0o755); err != nil {
				return fmt.Errorf("chmod %s: %w", d, err)
			}
		}
	}
	return nil
}

// AllowService lets project user uid reach port on wsm0, by adding the
// element uid . wsm0 . port to svc_allow4.
func (o *SystemOps) AllowService(ctx context.Context, uid, port int) error {
	script, err := netpolicy.AllowServiceScript(o.WSM0Addr, uid, port)
	if err != nil {
		return err
	}
	_, err = run(ctx, strings.NewReader(script), nil, "nft", "-f", "-")
	return err
}

// RevokeService removes that element; a missing one is not an error.
func (o *SystemOps) RevokeService(ctx context.Context, uid, port int) error {
	script, err := netpolicy.RevokeServiceScript(o.WSM0Addr, uid, port)
	if err != nil {
		return err
	}
	_, err = run(ctx, strings.NewReader(script), nil, "nft", "-f", "-")
	return err
}

// revokeAllServices removes every grant of uid from svc_allow4. Without
// table inet wsm there is nothing to remove.
func (o *SystemOps) revokeAllServices(ctx context.Context, uid int) error {
	out, err := run(ctx, nil, nil, "nft", "list", "tables")
	if err != nil {
		return err
	}
	if !hasLine(out, "table "+netpolicy.Table) {
		return nil
	}
	script, err := netpolicy.RevokeAllServicesScript(o.WSM0Addr, uid)
	if err != nil {
		return err
	}
	_, err = run(ctx, strings.NewReader(script), nil, "nft", "-f", "-")
	return err
}

// hasLine reports whether out has a line equal to line, ignoring spaces
// around it.
func hasLine(out, line string) bool {
	for _, l := range strings.Split(out, "\n") {
		if strings.TrimSpace(l) == line {
			return true
		}
	}
	return false
}
